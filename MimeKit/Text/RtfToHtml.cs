		/// <summary>
		/// The character formatting that is rendered as a <c>&lt;span style="..."&gt;</c>.
		/// </summary>
		readonly struct SpanFormat : IEquatable<SpanFormat>
		{
			public const int DefaultFontSize = RtfInterpreter.DefaultFontSize;

			public readonly RtfStateFlags Flags;
			public readonly RtfVerticalAlignment VerticalAlignment;
			public readonly int FontSize;
			public readonly int Foreground;
			public readonly int Background;

			public SpanFormat (RtfInterpreter rtf)
			{
				ref readonly var state = ref rtf.State;

				Flags = state.Flags & (RtfStateFlags.Bold | RtfStateFlags.Italic | RtfStateFlags.Underline | RtfStateFlags.Strike);
				VerticalAlignment = state.VerticalAlignment;
				// A font size of 0 can only come from a malformed \fs0, which would make the text invisible.
				FontSize = state.FontSize > 0 ? state.FontSize : DefaultFontSize;

				// RTF 1.9.1, "Color Table": \cfN and \cbN are indexes into the color table. The first entry is
				// conventionally left empty to represent the automatic (default) color, and \cf0/\cb0 (which are
				// also the implicit defaults) are used by writers to mean "auto" even when that entry is defined,
				// so index 0, like an undefined entry, is rendered using the default color.
				Foreground = state.ForegroundColor > 0 ? rtf.GetColor (state.ForegroundColor) : -1;
				Background = state.BackgroundColor > 0 ? rtf.GetColor (state.BackgroundColor) : -1;
			}

			public bool IsDefault {
				get {
					return Flags == 0 && VerticalAlignment == RtfVerticalAlignment.Baseline && FontSize == DefaultFontSize &&
						Foreground == -1 && Background == -1;
				}
			}

			public bool Equals (SpanFormat other)
			{
				return Flags == other.Flags && VerticalAlignment == other.VerticalAlignment && FontSize == other.FontSize &&
					Foreground == other.Foreground && Background == other.Background;
			}

			public override bool Equals (object? obj)
			{
				return obj is SpanFormat other && Equals (other);
			}

			public override int GetHashCode ()
			{
				return ((int) Flags ^ ((int) VerticalAlignment << 8) ^ (FontSize << 12)) ^ Foreground ^ (Background * 31);
			}

			public string ToCss (StringBuilder builder)
			{
				builder.Clear ();

				if ((Flags & RtfStateFlags.Bold) != 0)
					builder.Append ("font-weight: bold; ");

				if ((Flags & RtfStateFlags.Italic) != 0)
					builder.Append ("font-style: italic; ");

				if ((Flags & (RtfStateFlags.Underline | RtfStateFlags.Strike)) != 0) {
					builder.Append ("text-decoration:");
					if ((Flags & RtfStateFlags.Underline) != 0)
						builder.Append (" underline");
					if ((Flags & RtfStateFlags.Strike) != 0)
						builder.Append (" line-through");
					builder.Append ("; ");
				}

				switch (VerticalAlignment) {
				case RtfVerticalAlignment.Superscript: builder.Append ("vertical-align: super; "); break;
				case RtfVerticalAlignment.Subscript: builder.Append ("vertical-align: sub; "); break;
				}

				if (FontSize != DefaultFontSize) {
					// Half-points to points.
					builder.Append ("font-size: ");
					builder.Append ((FontSize / 2).ToString (CultureInfo.InvariantCulture));
					if ((FontSize & 1) != 0)
						builder.Append (".5");
					builder.Append ("pt; ");
				}

				if (Foreground != -1)
					AppendColor (builder, "color: ", Foreground);

				if (Background != -1)
					AppendColor (builder, "background-color: ", Background);

				// Remove the trailing space.
				builder.Length--;

				return builder.ToString ();
			}

			static void AppendColor (StringBuilder builder, string property, int rgb)
			{
				builder.Append (property);
				builder.Append ('#');
				builder.Append (rgb.ToString ("X6", CultureInfo.InvariantCulture));
				builder.Append ("; ");
			}
		}

		/// <summary>
		/// Receives the content of the RTF document and either renders it as HTML or, for documents
		/// that encapsulate HTML, collects the extracted HTML so that <see cref="EncapsulatedHtmlReader"/>
		/// can feed it to an <see cref="HtmlTokenizer"/>.
		/// </summary>
		sealed class HtmlHandler : RtfContentHandler
		{
			static readonly char[] Tab = { '\u00A0', '\u00A0', '\u00A0', '\u00A0' };
			static readonly char[] Nbsp = { '\u00A0' };
			static readonly char[] CrLf = { '\r', '\n' };

			readonly List<RtfToHtmlTagContext> stack = new List<RtfToHtmlTagContext> ();
			readonly StringBuilder css = new StringBuilder ();

			// Documents typically reuse a small number of distinct character formats, so the CSS for each is
			// cached rather than rebuilt for every span. The cache is bounded (and simply cleared when full) so
			// that a document with many distinct formats cannot make it grow without limit.
			const int MaxCssCacheEntries = 256;
			readonly Dictionary<SpanFormat, string> cssCache = new Dictionary<SpanFormat, string> ();
			readonly HtmlTagCallback callback;
			readonly RtfHtmlObjectPlaceholderCallback? placeholderCallback;
			readonly RtfToHtml converter;
			readonly TextWriter output;
			HtmlWriter? htmlWriter;

			// Render mode state.
			SpanFormat spanFormat;
			string? href;
			int placeholderIndex;
			bool lastWasSpace;

			// Extract mode state: a queue of extracted HTML characters waiting to be read.
			char[] extracted = Array.Empty<char> ();
			int extractedIndex, extractedLength;

			public HtmlHandler (RtfToHtml converter, TextWriter output)
			{
				callback = converter.HtmlTagCallback ?? DefaultHtmlTagCallback;
				placeholderCallback = converter.ObjectPlaceholderCallback;
				this.converter = converter;
				this.output = output;
			}

			public ConversionMode Mode {
				get; private set;
			}

			public override void OnBegin (RtfInterpreter rtf)
			{
				// [MS-OXRTFEX] 2.2.3.1: by now, the recognition window has closed, so FromHtml is final.
				if (rtf.FromHtml && rtf.ExtractHtml) {
					Mode = ConversionMode.Extract;
					return;
				}

				// Make sure that \htmlrtf content is rendered and \htmltag destinations are skipped for the
				// remainder of the document, as an RTF reader that does not support de-encapsulation would.
				rtf.ExtractHtml = false;
				Mode = ConversionMode.Render;

				if (!converter.OutputHtmlFragment)
					output.Write ("<html><body>");

				converter.WriteHeader (output);

				htmlWriter = new HtmlWriter (output, true);
			}

			#region Extract mode

			void Append (char[] buffer, int index, int count)
			{
				if (extractedIndex == extractedLength) {
					extractedIndex = extractedLength = 0;
				} else if (extractedIndex > 0) {
					Buffer.BlockCopy (extracted, extractedIndex * 2, extracted, 0, (extractedLength - extractedIndex) * 2);
					extractedLength -= extractedIndex;
					extractedIndex = 0;
				}

				// The interpreter emits a bounded amount of content per Step(), and the reader drains the queue
				// before stepping again, so this buffer never grows beyond a small multiple of the token size.
				if (extractedLength + count > extracted.Length)
					Array.Resize (ref extracted, Math.Max (extractedLength + count, Math.Max (256, extracted.Length * 2)));

				Buffer.BlockCopy (buffer, index * 2, extracted, extractedLength * 2, count * 2);
				extractedLength += count;
			}

			public int ExtractedCount {
				get { return extractedLength - extractedIndex; }
			}

			public int ReadExtracted (char[] buffer, int index, int count)
			{
				int n = Math.Min (count, extractedLength - extractedIndex);

				Buffer.BlockCopy (extracted, extractedIndex * 2, buffer, index * 2, n * 2);
				extractedIndex += n;

				return n;
			}

			public void SkipExtracted ()
			{
				extractedIndex++;
			}

			public int PeekExtracted ()
			{
				return extractedIndex < extractedLength ? extracted[extractedIndex] : -1;
			}

			#endregion

			#region Render mode

			int IndexOf (HtmlTagId id)
			{
				for (int i = stack.Count - 1; i >= 0; i--) {
					if (stack[i].TagId == id)
						return i;
				}

				return -1;
			}

			void Open (RtfToHtmlTagContext ctx)
			{
				if (!SuppressContent (stack))
					callback (ctx, htmlWriter!);

				stack.Add (ctx);
			}

			void CloseTo (int count)
			{
				while (stack.Count > count) {
					var ctx = stack[stack.Count - 1];
					stack.RemoveAt (stack.Count - 1);

					if (ctx.TagId == HtmlTagId.A)
						href = null;

					if (SuppressContent (stack) || ctx.DeleteEndTag)
						continue;

					ctx.SetIsEndTag (true);

					if (ctx.InvokeCallbackForEndTag)
						callback (ctx, htmlWriter!);
					else
						ctx.WriteTag (htmlWriter!);

					if (ctx.TagId == HtmlTagId.Div || ctx.TagId == HtmlTagId.TR || ctx.TagId == HtmlTagId.Table)
						htmlWriter!.WriteMarkupText (Environment.NewLine);
				}
			}

			void Close (HtmlTagId id)
			{
				int index = IndexOf (id);

				if (index != -1)
					CloseTo (index);
			}

			void OpenTable ()
			{
				if (IndexOf (HtmlTagId.Table) == -1)
					Open (new RtfToHtmlTagContext (HtmlTagId.Table));

				if (IndexOf (HtmlTagId.TR) == -1)
					Open (new RtfToHtmlTagContext (HtmlTagId.TR));

				if (IndexOf (HtmlTagId.TD) == -1)
					Open (new RtfToHtmlTagContext (HtmlTagId.TD));
			}

			// Opens the block-level elements (table > tr > td > div) that the current content belongs in.
			void OpenBlock (RtfInterpreter rtf)
			{
				ref readonly var state = ref rtf.State;

				// RTF 1.9.1, "Table Definitions": paragraphs that belong to a table are marked with \intbl.
				// Since \pard resets \intbl, content that follows the last row of a table ends the table.
				if (state.InTable)
					OpenTable ();
				else
					Close (HtmlTagId.Table);

				if (IndexOf (HtmlTagId.Div) != -1)
					return;

				// RTF 1.9.1, "Paragraph Formatting Properties": \ql, \qc, \qr and \qj. Alignment is a paragraph
				// property, so the alignment in effect when the paragraph's first content is seen is used.
				var ctx = state.Alignment switch {
					RtfAlignment.Center => new RtfToHtmlTagContext (HtmlTagId.Div, new HtmlAttribute (HtmlAttributeId.Style, "text-align: center;")),
					RtfAlignment.Right => new RtfToHtmlTagContext (HtmlTagId.Div, new HtmlAttribute (HtmlAttributeId.Style, "text-align: right;")),
					RtfAlignment.Justify => new RtfToHtmlTagContext (HtmlTagId.Div, new HtmlAttribute (HtmlAttributeId.Style, "text-align: justify;")),
					_ => new RtfToHtmlTagContext (HtmlTagId.Div),
				};

				Open (ctx);
				lastWasSpace = true;
			}

			// Opens the inline elements (a > span) needed for the current character formatting, closing any
			// that no longer apply. Spans are never nested, so the depth of the output is bounded regardless
			// of how the RTF groups are nested.
			void OpenInline (RtfInterpreter rtf)
			{
				var link = rtf.State.Hyperlink;
				var format = new SpanFormat (rtf);
				int index;

				if ((index = IndexOf (HtmlTagId.A)) != -1 && !string.Equals (href, link, StringComparison.Ordinal))
					CloseTo (index);

				if ((index = IndexOf (HtmlTagId.Span)) != -1 && !format.Equals (spanFormat))
					CloseTo (index);

				if (link != null && IndexOf (HtmlTagId.A) == -1) {
					Open (new RtfToHtmlTagContext (HtmlTagId.A, new HtmlAttribute (HtmlAttributeId.Href, link)));
					href = link;
				}

				if (!format.IsDefault && IndexOf (HtmlTagId.Span) == -1) {
					Open (new RtfToHtmlTagContext (HtmlTagId.Span, new HtmlAttribute (HtmlAttributeId.Style, GetCss (format))));
					spanFormat = format;
				}
			}

			string GetCss (SpanFormat format)
			{
				if (!cssCache.TryGetValue (format, out var value)) {
					if (cssCache.Count >= MaxCssCacheEntries)
						cssCache.Clear ();

					value = format.ToCss (css);
					cssCache.Add (format, value);
				}

				return value;
			}

			// HTML collapses whitespace, but whitespace in RTF is significant. Runs of spaces are preserved
			// by alternating them with non-breaking spaces and tabs are approximated with non-breaking spaces.
			void WriteText (char[] buffer, int index, int count)
			{
				int endIndex = index + count;
				int startIndex = index;

				for (int i = index; i < endIndex; i++) {
					var c = buffer[i];

					if (c == ' ') {
						if (lastWasSpace) {
							htmlWriter!.WriteText (buffer, startIndex, i - startIndex);
							htmlWriter.WriteText (Nbsp, 0, 1);
							startIndex = i + 1;
							lastWasSpace = false;
						} else {
							lastWasSpace = true;
						}
					} else if (c == '\t') {
						htmlWriter!.WriteText (buffer, startIndex, i - startIndex);
						htmlWriter.WriteText (Tab, 0, Tab.Length);
						startIndex = i + 1;
						lastWasSpace = false;
					} else {
						lastWasSpace = false;
					}
				}

				if (startIndex < endIndex)
					htmlWriter!.WriteText (buffer, startIndex, endIndex - startIndex);
			}

			void WriteLineBreak ()
			{
				var ctx = new RtfToHtmlTagContext (HtmlTagId.Br);

				if (!SuppressContent (stack))
					callback (ctx, htmlWriter!);

				lastWasSpace = true;
			}

			public void Finish ()
			{
				CloseTo (0);
				htmlWriter!.Flush ();
				htmlWriter.Dispose ();
				htmlWriter = null;

				converter.WriteFooter (output);

				if (!converter.OutputHtmlFragment)
					output.Write ("</body></html>");
			}

			#endregion

			public override void OnText (RtfInterpreter rtf, char[] buffer, int index, int count)
			{
				if (Mode == ConversionMode.Extract) {
					// [MS-OXRTFEX] 2.2.3.2: text outside of \htmltag destinations (that is not suppressed by
					// \htmlrtf) is copied to the output; it is already HTML.
					Append (buffer, index, count);
					return;
				}

				OpenBlock (rtf);
				OpenInline (rtf);

				if (!SuppressContent (stack))
					WriteText (buffer, index, count);
			}

			public override void OnHtmlTag (RtfInterpreter rtf, char[] buffer, int index, int count)
			{
				// Only reported while de-encapsulating, i.e. in extract mode. [MS-OXRTFEX] 2.2.3.2: the content
				// of an HTMLTAG destination is copied to the output.
				if (Mode == ConversionMode.Extract)
					Append (buffer, index, count);
			}

			public override void OnParagraph (RtfInterpreter rtf)
			{
				if (Mode == ConversionMode.Extract) {
					// [MS-OXRTFEX] 2.2.3.2: \par is converted to CRLF.
					Append (CrLf, 0, 2);
					return;
				}

				// A paragraph with no content would be an empty <div> that browsers collapse, so give it a
				// line break to preserve the vertical space that the RTF paragraph occupies.
				bool empty = IndexOf (HtmlTagId.Div) == -1;

				OpenBlock (rtf);

				if (empty)
					WriteLineBreak ();

				Close (HtmlTagId.Div);
			}

			public override void OnLineBreak (RtfInterpreter rtf)
			{
				if (Mode == ConversionMode.Extract) {
					// [MS-OXRTFEX] 2.2.3.2: \line is converted to CRLF.
					Append (CrLf, 0, 2);
					return;
				}

				OpenBlock (rtf);
				OpenInline (rtf);
				WriteLineBreak ();
			}

			public override void OnCell (RtfInterpreter rtf)
			{
				if (Mode == ConversionMode.Extract)
					return;

				// RTF 1.9.1, "Table Definitions": \cell terminates a cell (which may be empty).
				OpenTable ();
				Close (HtmlTagId.TD);
			}

			public override void OnRow (RtfInterpreter rtf)
			{
				if (Mode == ConversionMode.Extract)
					return;

				// RTF 1.9.1, "Table Definitions": \row terminates a row.
				if (IndexOf (HtmlTagId.Table) == -1)
					Open (new RtfToHtmlTagContext (HtmlTagId.Table));

				if (IndexOf (HtmlTagId.TR) == -1)
					Open (new RtfToHtmlTagContext (HtmlTagId.TR));

				Close (HtmlTagId.TR);
			}

			public override void OnObjectPlaceholder (RtfInterpreter rtf)
			{
				// [MS-OXRTFEX] 2.2.3.4: the placeholders are only meaningful when the RTF itself is rendered. HTML
				// that is extracted from the RTF refers to its attachments by itself (e.g. using cid: URLs).
				if (Mode == ConversionMode.Extract)
					return;

				// The index is advanced even if the callback is not invoked so that the placeholders stay in lock
				// step with the attachment list.
				int index = placeholderIndex;

				if (placeholderIndex < int.MaxValue)
					placeholderIndex++;

				if (placeholderCallback is null)
					return;

				OpenBlock (rtf);
				OpenInline (rtf);

				if (!SuppressContent (stack))
					placeholderCallback (index, htmlWriter!);

				lastWasSpace = false;
			}
		}

		/// <summary>
		/// A <see cref="TextReader"/> that incrementally de-encapsulates HTML from an RTF document so that it
		/// can be streamed into an <see cref="HtmlTokenizer"/> without buffering the entire document.
		/// </summary>
		sealed class EncapsulatedHtmlReader : TextReader
		{
			readonly RtfInterpreter interpreter;
			readonly HtmlHandler handler;
			bool eof;

			public EncapsulatedHtmlReader (RtfInterpreter interpreter, HtmlHandler handler)
			{
				this.interpreter = interpreter;
				this.handler = handler;
			}

			bool Fill ()
			{
				while (handler.ExtractedCount == 0 && !eof)
					eof = !interpreter.Step ();

				return handler.ExtractedCount > 0;
			}

			public override int Peek ()
			{
				return Fill () ? handler.PeekExtracted () : -1;
			}

			public override int Read ()
			{
				int c = Peek ();

				if (c != -1)
					handler.SkipExtracted ();

				return c;
			}

			public override int Read (char[] buffer, int index, int count)
			{
				if (count == 0 || !Fill ())
					return 0;

				return handler.ReadExtracted (buffer, index, count);
			}
		}

		// The encapsulated HTML is just as untrusted as any other HTML, so it is filtered by the same logic as HtmlToHtml.
		void ConvertExtractedHtml (TextReader reader, TextWriter writer)
		{
			var converter = new HtmlToHtml {
				OutputHtmlFragment = OutputHtmlFragment,
				NoScriptHandling = NoScriptHandling,
				MaxElementDepth = maxElementDepth,
				HtmlTagCallback = HtmlTagCallback
			};

			WriteHeader (writer);
			converter.ConvertHtml (reader, writer);
			WriteFooter (writer);
		}

		/// <summary>
		/// Convert the contents of <paramref name="reader"/> from the <see cref="InputFormat"/> to the
		/// <see cref="OutputFormat"/> and uses the <paramref name="writer"/> to write the resulting text.
		/// </summary>
		/// <remarks>
		/// Converts the contents of <paramref name="reader"/> from the <see cref="InputFormat"/> to the
		/// <see cref="OutputFormat"/> and uses the <paramref name="writer"/> to write the resulting text.
		/// </remarks>
		/// <param name="reader">The text reader.</param>
		/// <param name="writer">The text writer.</param>
		/// <exception cref="System.ArgumentNullException">
		/// <para><paramref name="reader"/> is <see langword="null"/>.</para>
		/// <para>-or-</para>
		/// <para><paramref name="writer"/> is <see langword="null"/>.</para>
		/// </exception>
		public override void Convert (TextReader reader, TextWriter writer)
		{
			if (reader is null)
				throw new ArgumentNullException (nameof (reader));

			if (writer is null)
				throw new ArgumentNullException (nameof (writer));

			var handler = new HtmlHandler (this, writer);
			var interpreter = new RtfInterpreter (reader, handler, MaxGroupDepth, MaxFontTableEntries, MaxColorTableEntries) {
				ExtractHtml = ExtractEncapsulatedHtml
			};

			// [MS-OXRTFEX] 2.2.3.1: whether a document encapsulates HTML can only be determined after the first
			// few tokens have been read. The interpreter notifies the handler (via OnBegin) once that is known and
			// before any content is reported, at which point the handler decides how to convert the document.
			while (handler.Mode == ConversionMode.Undecided && interpreter.Step ())
				;

			if (handler.Mode == ConversionMode.Extract) {
				// Any content reported along with OnBegin has been queued by the handler and will be read first.
				using (var html = new EncapsulatedHtmlReader (interpreter, handler))
					ConvertExtractedHtml (html, writer);
			} else {
				while (interpreter.Step ())
					;

				handler.Finish ();
			}
		}

		/// <summary>
		/// Counts the attachment placeholders that <see cref="Convert(TextReader, TextWriter)"/> would report to the
		/// <see cref="ObjectPlaceholderCallback"/>.
		/// </summary>
		/// <remarks>
		/// [MS-OXRTFEX] 2.2.3.4: the placeholders are matched with the attachments only if their numbers are equal,
		/// which has to be known before the document is rendered.
		/// </remarks>
		/// <returns>The number of placeholders (saturating at <see cref="int.MaxValue"/>), or <c>-1</c> if the HTML
		/// encapsulated within the document would be extracted instead of rendering the RTF.</returns>
		internal int CountObjectPlaceholders (TextReader reader, CancellationToken cancellationToken)
		{
			var counter = new PlaceholderCounter ();
			var interpreter = new RtfInterpreter (reader, counter, MaxGroupDepth, MaxFontTableEntries, MaxColorTableEntries) {
				ExtractHtml = ExtractEncapsulatedHtml
			};

			while (!counter.Extract && interpreter.Step ())
				cancellationToken.ThrowIfCancellationRequested ();

			return counter.Extract ? -1 : counter.Count;
		}

		/// <summary>
		/// Determines whether <see cref="Convert(TextReader, TextWriter)"/> would extract the HTML encapsulated within
		/// the document rather than render the RTF.
		/// </summary>
		/// <remarks>
		/// Only the beginning of the document is normally read ([MS-OXRTFEX] 2.2.3.1).
		/// </remarks>
		/// <returns><see langword="true"/> if the encapsulated HTML would be extracted; otherwise, <see langword="false"/>.</returns>
		internal bool ExtractsEncapsulatedHtml (TextReader reader, CancellationToken cancellationToken)
		{
			var counter = new PlaceholderCounter ();
			var interpreter = new RtfInterpreter (reader, counter, MaxGroupDepth, MaxFontTableEntries, MaxColorTableEntries) {
				ExtractHtml = ExtractEncapsulatedHtml
			};

			while (!counter.Begun && interpreter.Step ())
				cancellationToken.ThrowIfCancellationRequested ();

			return counter.Extract;
		}

		internal sealed class PlaceholderCounter : RtfContentHandler
		{
			public bool Extract;
			public bool Begun;
			public int Count;

			public override void OnBegin (RtfInterpreter rtf)
			{
				Begun = true;

				// Mirrors HtmlHandler.OnBegin.
				if (rtf.FromHtml && rtf.ExtractHtml)
					Extract = true;
				else
					rtf.ExtractHtml = false;
			}

			public override void OnObjectPlaceholder (RtfInterpreter rtf)
			{
				if (Count < int.MaxValue)
					Count++;
			}
		}
	}
