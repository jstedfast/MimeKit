	/// <summary>
	/// An RTF to HTML converter.
	/// </summary>
	/// <remarks>
	/// <para>Used to convert Rich Text Format (RTF) documents into HTML.</para>
	/// <para>The converter implements the subset of the Rich Text Format (RTF) Specification, version 1.9.1,
	/// that can be meaningfully represented in HTML: character sets and code pages, Unicode escapes,
	/// paragraphs and paragraph alignment, line breaks, tables, bold, italic, underline, strikethrough,
	/// superscript, subscript, font sizes, foreground and background colors, and <c>HYPERLINK</c> fields.
	/// Destinations that do not contain document text (such as pictures, embedded objects, style sheets and
	/// document properties) are skipped, as is hidden text. The attachment placeholders (<c>\objattph</c>) that
	/// Microsoft Outlook and Exchange write are reported to the <see cref="ObjectPlaceholderCallback"/>.</para>
	/// <para>RTF documents that encapsulate HTML (such as those generated by Microsoft Outlook and Exchange),
	/// as described by [MS-OXRTFEX], have their original HTML extracted rather than having the RTF rendering
	/// of that HTML converted back into HTML. See <see cref="ExtractEncapsulatedHtml"/>.</para>
	/// <para>The converter is designed to be resilient against hostile input. Its memory usage does not depend
	/// on the size of the input: font table, color table and group nesting resources are bounded by
	/// <see cref="MaxFontTableEntries"/>, <see cref="MaxColorTableEntries"/> and <see cref="MaxGroupDepth"/>,
	/// embedded binary data (<c>\binN</c>) is skipped without being buffered, and only hyperlinks with
	/// <c>http</c>, <c>https</c>, <c>mailto</c>, <c>ftp</c> or <c>tel</c> URL schemes are rendered as links.</para>
	/// <note type="note">Since RTF is a 7-bit format in which non-ASCII characters are escaped, the
	/// <see cref="TextConverter.InputEncoding"/> defaults to ISO-8859-1 so that every byte of the input
	/// maps to exactly one character. The code page used to decode escaped characters is determined by the
	/// document itself (<c>\ansicpg</c>, <c>\fcharset</c> and <c>\cpg</c>).</note>
	/// <note type="security">
	/// <para>Encapsulated HTML is extracted as-is (subject to the <see cref="HtmlTagCallback"/>), exactly like
	/// <see cref="HtmlToHtml"/> would output it. <see cref="RtfToHtml"/> is not an HTML sanitizer. For
	/// displaying untrusted content, use a dedicated HTML sanitizer library.</para>
	/// </note>
	/// </remarks>
	public class RtfToHtml : TextConverter
	{
